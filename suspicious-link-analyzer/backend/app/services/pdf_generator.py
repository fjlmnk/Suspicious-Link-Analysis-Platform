from io import BytesIO
from datetime import datetime
from typing import Dict, Any

from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable

class PDFReportGenerator:
    @staticmethod
    def generate(report_data: Dict[str, Any]) -> bytes:
        buffer = BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            rightMargin=36,
            leftMargin=36,
            topMargin=36,
            bottomMargin=36
        )

        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            'DocTitle',
            parent=styles['Heading1'],
            fontName='Helvetica-Bold',
            fontSize=20,
            textColor=colors.HexColor('#0f172a'),
            spaceAfter=6
        )
        subtitle_style = ParagraphStyle(
            'DocSubtitle',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=10,
            textColor=colors.HexColor('#64748b'),
            spaceAfter=15
        )
        h2_style = ParagraphStyle(
            'SectionH2',
            parent=styles['Heading2'],
            fontName='Helvetica-Bold',
            fontSize=13,
            textColor=colors.HexColor('#1e293b'),
            spaceBefore=12,
            spaceAfter=6
        )
        normal_style = ParagraphStyle(
            'BodyTextCustom',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=9,
            textColor=colors.HexColor('#334155'),
            leading=13
        )
        code_style = ParagraphStyle(
            'CodeText',
            parent=styles['Normal'],
            fontName='Courier',
            fontSize=9,
            textColor=colors.HexColor('#0284c7')
        )

        elements = []

        # Header
        elements.append(Paragraph("SUSPICIOUS LINK ANALYSIS REPORT", title_style))
        elements.append(Paragraph(f"Generated by Threat Intelligence Engine &bull; {datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S UTC')}", subtitle_style))
        elements.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor('#cbd5e1'), spaceAfter=15))

        # Overview Table
        threat_level = str(report_data.get('threat_level', 'UNKNOWN')).upper()
        if threat_level == 'DANGEROUS':
            badge_color = colors.HexColor('#ef4444')
            badge_text_color = colors.white
        elif threat_level == 'SUSPICIOUS':
            badge_color = colors.HexColor('#f59e0b')
            badge_text_color = colors.white
        else:
            badge_color = colors.HexColor('#10b981')
            badge_text_color = colors.white

        overview_data = [
            [Paragraph("<b>Target URL:</b>", normal_style), Paragraph(str(report_data.get('url', '')), code_style)],
            [Paragraph("<b>Report ID:</b>", normal_style), Paragraph(f"#{report_data.get('report_id', '')}", normal_style)],
            [Paragraph("<b>Scan Request ID:</b>", normal_style), Paragraph(f"#{report_data.get('request_id', '')}", normal_style)],
            [Paragraph("<b>Overall Threat Level:</b>", normal_style), Paragraph(f"<b>{threat_level}</b>", ParagraphStyle('Badge', parent=normal_style, textColor=badge_color, fontName='Helvetica-Bold'))],
            [Paragraph("<b>Numerical Risk Score:</b>", normal_style), Paragraph(f"<b>{report_data.get('risk_score', 0)} / 100</b>", normal_style)],
            [Paragraph("<b>Timestamp:</b>", normal_style), Paragraph(str(report_data.get('generated_at', '')), normal_style)],
        ]

        overview_table = Table(overview_data, colWidths=[140, 400])
        overview_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#f8fafc')),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e2e8f0')),
            ('PADDING', (0, 0), (-1, -1), 6),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ]))
        elements.append(overview_table)
        elements.append(Spacer(1, 15))

        # Threat Intelligence Providers Table
        elements.append(Paragraph("Security Intelligence Providers Verdicts", h2_style))
        verdicts = report_data.get('provider_verdicts', [])
        
        provider_rows = [
            [
                Paragraph("<b>Provider</b>", normal_style),
                Paragraph("<b>Verdict</b>", normal_style),
                Paragraph("<b>Detections</b>", normal_style),
                Paragraph("<b>Details / Category</b>", normal_style),
                Paragraph("<b>Status</b>", normal_style)
            ]
        ]

        for v in verdicts:
            is_mal = v.get('is_malicious', False)
            verdict_text = "MALICIOUS" if is_mal else "CLEAN"
            v_color = colors.HexColor('#ef4444') if is_mal else colors.HexColor('#10b981')

            provider_rows.append([
                Paragraph(str(v.get('provider_name', '')), normal_style),
                Paragraph(f"<b>{verdict_text}</b>", ParagraphStyle('PvColor', parent=normal_style, textColor=v_color)),
                Paragraph(str(v.get('detection_count', 0)), normal_style),
                Paragraph(str(v.get('category', '-')), normal_style),
                Paragraph(str(v.get('provider_status', 'OK')), normal_style),
            ])

        if len(provider_rows) == 1:
            provider_rows.append([Paragraph("No provider data available", normal_style), "", "", "", ""])

        pv_table = Table(provider_rows, colWidths=[120, 80, 70, 200, 70])
        pv_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#e2e8f0')),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
            ('PADDING', (0, 0), (-1, -1), 5),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ]))
        elements.append(pv_table)
        elements.append(Spacer(1, 15))

        # Detailed Explanation
        elements.append(Paragraph("Threat Analysis Explanation & Guidance", h2_style))
        explanation_raw = report_data.get('explanation', 'No explanation provided.')
        for line in explanation_raw.split("\n"):
            line = line.strip()
            if not line:
                elements.append(Spacer(1, 4))
            elif line.startswith("-") or line.startswith("1.") or line.startswith("2.") or line.startswith("3."):
                elements.append(Paragraph(f"&nbsp;&bull; {line.lstrip('-123. ')}", normal_style))
            else:
                elements.append(Paragraph(line, normal_style))

        elements.append(Spacer(1, 20))
        elements.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor('#e2e8f0'), spaceAfter=10))
        elements.append(Paragraph("Confidential &bull; Security Operations Audit Record &bull; Suspicious Link Analysis Platform", subtitle_style))

        doc.build(elements)
        buffer.seek(0)
        return buffer.getvalue()
